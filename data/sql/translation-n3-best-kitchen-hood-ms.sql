## Apa yang menjadikan hood dapur terbaik untuk dapur Malaysia

Masakan Malaysia memang mencabar sesebuah hood. Menumis, memasak sambal dan menggoreng menghasilkan lebih banyak asap dan wap minyak dalam beberapa minit berbanding ketuhar dalam sejam, jadi hood yang direka untuk dapur Barat selalunya tidak cukup kuat di sini. Empat perkara menentukan sama ada hood mampu bertahan.

**Aliran udara (m³/h).** Berapa banyak udara yang disedut oleh hood. Rangkaian VATTI bermula dari 1,860 m³/h hingga 3,690 m³/h, dan setiap model lebih daripada cukup untuk dapur biasa. Aliran udara yang lebih tinggi paling penting untuk dapur terbuka, kerana asap boleh merebak ke seluruh ruang.

**Tekanan statik (Pa).** Sekuat mana hood boleh menolak udara itu melalui saluran yang melawan. Inilah angka yang paling penting di kondo, kerana salurannya panjang, berliku dan dikongsi dengan unit di atas dan di bawah. Rangkaiannya dari 420 Pa hingga 1,700 Pa.

**Bunyi (dB).** Hood yang terlalu bising akan dimatikan sebelum asap habis disedut. Rangkaiannya dari 46.5 dB hingga 54 dB, dan setiap 3 dB ialah perbezaan yang boleh didengar.

**Tapisan minyak (%).** Berapa banyak minyak yang ditahan di dalam hood dan tidak dihantar ke saluran atau ke kabinet anda. Kebanyakan hood VATTI menapis 92% minyak, dan V959 menapis 95%.

