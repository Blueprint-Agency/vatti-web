## Apa yang menjadikan dapur gas terbaik untuk dapur Malaysia

Masakan Malaysia banyak menuntut daripada dapur gas. Kuali memerlukan api yang kuat dan tertumpu untuk menumis dengan betul, kari atau sup tulang pula memerlukan api kecil yang stabil selama sejam, dan kedua-duanya selalu berlaku pada malam yang sama. Lima perkara menentukan sama ada dapur gas mampu bertahan.

**Kuasa api (kW).** Berapa banyak haba yang dihasilkan tungku pada api penuh. Rangkaian dapur gas VATTI bermula dari 3.8 kW hingga 6.0 kW. Untuk wok hei, cari 4.5 kW atau lebih pada tungku utama.

**Kecekapan haba (%).** Berapa banyak haba gas yang masuk ke kuali, bukan ke udara di sekelilingnya. Tungku yang lebih cekap memanaskan kuali lebih cepat pada api yang sama. VATTI mencatat 73% pada C836G, 65% pada C821G dan C861G, dan 63% pada C822G dan C823G.

**Tungku dan penyokong kuali.** Tungku tembaga kekal bentuknya di bawah haba tinggi, dan penyokong besi tuang memastikan kuali berat tetap stabil. Lima daripada sembilan dapur gas VATTI mempunyai kedua-duanya.

**Keselamatan.** Setiap dapur gas VATTI menyenaraikan peranti keselamatan; pada lukisan C822G dan C823G ia ialah peranti kegagalan api termokopel, yang memutuskan gas jika api terpadam. C835G, C836G dan C861G menambah pemutus automatik apabila periuk kering atau terlalu panas, dan tujuh daripada sembilan mempunyai tombol kunci kanak-kanak.

**Permukaan: kaca atau keluli tahan karat.** Kaca tempered mudah dilap dan sesuai untuk dapur moden; keluli tahan karat tahan digunakan berat setiap hari. Panduan kami tentang [dapur gas kaca atau keluli tahan karat](/buying-guide/glass-vs-stainless-gas-hob-which-gas-hob-are-best/) membandingkan kedua-duanya.

