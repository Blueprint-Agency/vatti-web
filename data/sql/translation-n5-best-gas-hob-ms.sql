## Soalan lazim tentang dapur gas terbaik

**Apakah jenama dapur gas terbaik di Malaysia?**
Jenama tidak menentukan sama ada dapur gas sesuai untuk dapur anda; angkanya yang menentukan. Bandingkan kuasa api, kecekapan haba, ciri keselamatan dan saiz potongan. Setiap dapur gas VATTI menerbitkan angka itu pada halaman produknya, jadi anda boleh membandingkannya model demi model.

**Dapur gas mana yang terbaik untuk menumis dengan kuali?**
Yang mempunyai tungku utama yang kuat, kepala tungku tembaga dan penyokong besi tuang. Cari 4.5 kW atau lebih; C836G (5.5 kW) dan C822G (5.2 kW) ialah dapur dua tungku VATTI yang paling kuat, dan C720S memberi 5.2 kW pada kedua-dua tungku luarnya.

**Berapa kW yang perlu ada pada dapur gas?**
Untuk masakan harian Malaysia, 4.5 kW pada tungku utama ialah asas yang baik. Kuasa paling penting untuk menumis; untuk merebus, api yang boleh dikecilkan dan kekal menyala lebih penting.

**Dapur gas kaca atau keluli tahan karat, mana lebih baik?**
Kaca lebih mudah dilap dan nampak lebih kemas; keluli tahan karat tahan digunakan berat setiap hari. Pada dapur VATTI, kaca tempered dilindungi waranti seumur hidup daripada retak.

**Perlukah dapur gas ada peranti keselamatan?**
Ya. Peranti kegagalan api memutuskan gas jika api terpadam, sama ada kerana angin atau periuk melimpah. Setiap dapur gas VATTI menyenaraikan peranti keselamatan, dan C835G serta C836G menambah pemutus apabila kering dan apabila tiada periuk.

**Gas jenis apa yang diperlukan: LPG atau gas asli?**
Kedua-duanya digunakan di Malaysia: tong gas LPG di kebanyakan rumah dan gas asli melalui paip di sesetengah kawasan. Pastikan model itu ditetapkan untuk bekalan anda; C720S dan C821G menyenaraikan kedua-duanya pada lukisannya.

**Dapur gas saya tidak menyala. Apa yang perlu diperiksa?**
Biasanya bateri, pencucuh yang basah atau kotor, atau penutup tungku yang tidak duduk lurus. Panduan kami tentang [pencucuh dapur gas yang tidak berfungsi](/tips-tricks/gas-hob-igniter-not-working/) menerangkan cara membaikinya.

