## Wok cooking: where gas still wins

Much Malaysian cooking happens in a wok: char kuey teow, fried rice, sambal, stir-fried vegetables. A round-bottomed wok sits in a gas flame and heats up its sides as well as its base, and tossing the food through the flame is what gives it wok hei. An induction cooker only heats where the pan touches the glass, so a round wok rocks and heats at one point. A flat-bottomed wok works on induction, but you cannot lift it to toss without the heat cutting out.

If wok frying is your daily cooking, a gas stove is the better tool. The VATTI gas hobs run from 4.5 kW to 6.0 kW on the main burner, with the [C830G](/vatti-3-burner-gas-hob-c830g/) at the top of that range. The [C836G](/vatti-flexi-hob-c836g/) turns 73% of its gas into heat, the most in the range. Our guide to the [best gas hob in Malaysia](/buying-guide/best-gas-hob-malaysia/) compares them all.

## Where an induction cooker wins

- **No open flame.** Nothing to catch a sleeve or a kitchen towel, which matters with children around and in an open kitchen.
- **A cooler kitchen.** More of the heat goes into the pan and less into the room.
- **Precise low heat.** Simmering a curry, melting chocolate or keeping a soup warm is steadier than on a low flame.
- **Cleaning.** Spills land on flat glass that does not get as hot as a burner, so they do not bake on. Wipe once it cools.

## Cookware: the magnet test

Induction only works with pans that have iron in the base: cast iron, carbon steel and most stainless steel. Aluminium, copper, glass and clay pots do not work unless they have a steel plate in the base. Hold a fridge magnet to the bottom of the pan; if it sticks, the pan works on induction.

That includes the claypot. A claypot chicken rice or a bak kut teh simmered in clay needs a flame or a ceramic hob, not induction.

## Power cuts and gas

An induction cooker needs electricity, so it stops in a power cut. A gas stove keeps cooking as long as there is gas. If your area loses power often, or you want to be able to cook through an outage, keep a gas burner somewhere in the kitchen.

