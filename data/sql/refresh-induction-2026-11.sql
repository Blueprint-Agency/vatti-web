## How an induction cooker works

Under the glass of an induction cooker is a coil. When you switch it on, the coil makes a magnetic field that heats the base of an iron or steel pan directly. The glass itself is not the heater: it gets warm only from the pan sitting on it. That is why induction responds quickly when you turn it up or down, and why the kitchen stays cooler than with a flame.

A gas stove burns gas under the pan. You see the heat, you adjust it by eye, and the flame wraps around the sides of a round-bottomed wok. Some of that heat goes into the room rather than the pan.

