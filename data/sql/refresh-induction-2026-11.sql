## Induction cooker FAQs

**Is an induction cooker good for Malaysian cooking?**
For simmering, boiling, soups, curries and shallow frying, yes. For high-heat wok frying, a gas stove is better, because a round wok needs a flame around its sides.

**Can I use a wok on an induction cooker?**
Only a flat-bottomed wok with an iron or steel base. It will heat, but you cannot toss it in the air without the heat cutting out.

**Is an induction cooker safer than a gas stove?**
It has no open flame, and the glass is heated only by the pan, so it is less likely to start a fire. The surface is still hot after cooking; a residual heat warning, like the one on the VH-IC9-LA, tells you when.

**What happens to an induction cooker in a power cut?**
It stops working. A gas stove keeps going, which is one reason many homes keep a gas burner as well.

**Induction or ceramic?**
Both have a flat glass top. Induction heats the pan directly and only works with iron or steel pans; ceramic heats the glass and works with any pan. Our guide to [induction or ceramic cookers](/buying-guide/which-is-better-induction-or-ceramic-cooker/) compares them in full, and [common induction cooker problems](/buying-guide/induction-cooker-problems/) covers what to expect.

