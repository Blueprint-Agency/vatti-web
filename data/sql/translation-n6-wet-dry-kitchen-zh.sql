## 什么是湿厨房，什么是干厨房

名字说的是脏乱程度，不是地板湿不湿。**湿厨房**是为会产生油烟、油雾和蒸汽的烹饪而设：猛火爆炒、油炸、长时间煲汤、处理鱼和鸡。它通常是封闭的，多数靠近后门或后院，让气味和油污留在里面。

**干厨房**是为干净的烹饪而设：早餐、加热、烘焙、蒸煮、冲饮料和摆盘。它通常对饭厅或客厅开放，是家里门面的一部分，所以外观和噪音比单纯的马力更重要。

