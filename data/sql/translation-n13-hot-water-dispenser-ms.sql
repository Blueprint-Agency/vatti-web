Letakkan paip di sinki yang anda gunakan untuk mengisi cerek, cawan dan periuk nasi. Di rumah yang ada dapur basah dan dapur kering, biasanya itu dapur kering untuk minuman; panduan kami tentang [dapur basah dan dapur kering](/ms/panduan-membeli/dapur-basah-dan-dapur-kering/) menerangkan peralatan mana diletakkan di mana. Sistem bawah sinki sesuai untuk dapur kondominium, di mana dispenser berdiri dan botolnya mengambil ruang yang tiada.

## Soalan lazim water dispenser air panas

**Adakah water dispenser air panas lebih baik daripada cerek?**
Untuk isi rumah yang membuat beberapa minuman panas sehari, ya: air sedia pada suhu yang anda mahu tanpa menunggu ia mendidih dan sejuk. Cerek masih pilihan yang lebih mudah jika anda hanya menjerang air sekali atau dua kali sehari.

**Berapa suhu air dari water dispenser air panas?**
Bergantung pada dispenser. Banyak yang memberi satu suhu panas; VATTI One Tap memberi 45°C, 85°C atau 100°C, serta suhu bilik.

**Adakah water dispenser membersihkan air?**
Hanya jika ia ada penapis. Dispenser yang hanya memanaskan memberi air paip yang panas. One Tap menapis melalui membran RO sebelum memanaskan.

**Bolehkah saya dapat air sejuk dari One Tap?**
Tidak. Ia tiada tetapan air sejuk. Mod keempatnya ialah air yang ditapis pada suhu bilik.

**Perlukah saya menukar botol?**
Tidak dengan dispenser yang mengambil air dari bekalan air rumah. One Tap tiada botol; penapis yang perlu ditukar.

