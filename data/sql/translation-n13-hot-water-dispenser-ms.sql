Pemanas segera berfungsi sebaliknya: air melalui pemanas dalam perjalanan ke paip dan keluar pada suhu yang anda pilih. Tiada tangki air panas berdiri dalam almari. Pemanas VATTI V818WD berfungsi begini, di bawah sinki di sebelah penapis WDHG01.

