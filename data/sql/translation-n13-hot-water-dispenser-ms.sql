## Apa yang perlu disemak sebelum membeli

- **Tetapan suhu.** Satu tetapan panas cukup untuk teh; tetapan berasingan menjimatkan masa menunggu air sejuk untuk kopi atau susu. One Tap ada 45°C, 85°C dan 100°C, serta suhu bilik.
- **Aliran.** Paip yang perlahan tidak mengapa untuk segelas, tetapi menyusahkan untuk periuk. One Tap memberi 1.5 L seminit.
- **Penapisan.** Cari penapis sebelum pemanas, dan RO jika anda mahu penapisan paling halus.
- **Peringatan penapis.** Penapis yang sudah tamat hayat berhenti berfungsi tanpa memberitahu anda. One Tap ada peringatan tukar penapis. Lihat [berapa kerap menukar penapis air](/tips-tricks/how-often-replace-water-filter/).
