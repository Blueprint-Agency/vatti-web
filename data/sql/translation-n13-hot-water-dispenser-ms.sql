- **Ruang.** Ukur kabinet. Penapis WDHG01 berukuran 439 x 385 x 168 mm dan pemanas V818WD 175 x 295 x 120 mm; paip di atas kaunter setinggi 374 mm.
- **Air sejuk.** Jika anda mahu air sejuk, semak tetapan air sejuk sebelum perkara lain.

