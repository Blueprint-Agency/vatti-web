## 怎样的煤气炉才适合马来西亚厨房

马来西亚人的煮食方式对煤气炉要求很高。炒锅要强而集中的火才炒得出镬气，咖喱和肉骨茶却要小火稳稳地煲一个小时，而且两样常常在同一个晚上。一台炉头跟不跟得上，看以下五点。

**火力（kW）。**炉头开到最大时的发热量。VATTI 煤气炉系列从 3.8 kW 到 6.0 kW。想要镬气，主炉头最好有 4.5 kW 或以上。

**热效率（%）。**煤气的热量有多少进到锅里，而不是散到空气中。热效率越高，同样的火力热锅越快。VATTI 标示的数字是：C836G 73%，C821G 和 C861G 65%，C822G 和 C823G 63%。

**炉头和锅架。**铜炉头在高温下不易变形，铸铁锅架让沉重的炒锅放得稳。九款 VATTI 煤气炉中有五款两样都有。

**安全。**每一款 VATTI 煤气炉都列有安全装置；在 C822G 和 C823G 的图纸上，那是热电偶熄火保护装置，火一熄就会断气。C835G、C836G 和 C861G 还加上干烧和过热自动断气，九款中有七款设有童锁旋钮。

**台面：玻璃还是不锈钢。**钢化玻璃好擦，适合现代厨房；不锈钢经得起天天重度使用。我们的[玻璃与不锈钢煤气炉比较](/buying-guide/glass-vs-stainless-gas-hob-which-gas-hob-are-best/)有详细说明。

