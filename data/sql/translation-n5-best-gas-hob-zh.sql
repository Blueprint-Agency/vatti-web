## 煤气炉推荐常见问题

**煤气炉哪个牌子好？**
决定一台煤气炉适不适合你家的，是数字而不是牌子。比较火力、热效率、安全功能和开孔尺寸。每一款 VATTI 煤气炉都在产品页面列出这些数字，可以逐款比较。

**炒菜用哪种煤气炉最好？**
主炉头火力强、铜炉头、铸铁锅架的那种。最好有 4.5 kW 或以上；VATTI 的 C836G（5.5 kW）和 C822G（5.2 kW）是火力最强的双头炉，C720S 三头炉的左右两个炉头也各有 5.2 kW。

**煤气炉要多少 kW 才够？**
马来西亚家庭日常煮食，主炉头 4.5 kW 是不错的起点。火力对爆炒最重要；煲汤炖煮时，能调到很小又不会熄火更重要。

**玻璃还是不锈钢煤气炉比较好？**
玻璃好擦、看起来整洁；不锈钢经得起天天重度使用。VATTI 炉头的钢化玻璃享有终身防爆裂保修。

**煤气炉一定要有安全装置吗？**
要。熄火保护装置在火被风吹熄或汤汁溢出浇熄时自动断气。每一款 VATTI 煤气炉都列有安全装置，C835G 和 C836G 还加上干烧和无锅自动断气。

**用石油气（LPG）还是天然气？**
马来西亚两种都有：大多数家庭用石油气桶，部分地区有管道天然气。请确认型号适用于你家的气源；C720S 和 C821G 的图纸上两种都有列出。

**煤气炉点不着火，要检查什么？**
通常是电池、点火针潮湿或脏了，或炉盖没有放正。我们的[煤气炉点火器故障指南](/tips-tricks/gas-hob-igniter-not-working/)一步步说明解决方法。

