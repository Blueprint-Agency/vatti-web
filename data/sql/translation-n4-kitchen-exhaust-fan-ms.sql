## Kenapa masakan kuali perlukan hood

Masakan Malaysia menghasilkan lebih banyak asap dan minyak dalam beberapa minit berbanding kebanyakan dapur lain dalam satu malam. Menumis dengan api besar menghasilkan kepulan wap minyak yang naik dengan cepat dan luas. Exhaust fan di hujung bilik tidak dapat menarik kepulan itu ke tepi dengan cukup pantas; hood, yang duduk tidak jauh di atas kuali, berada betul-betul di laluannya.

Minyak lebih penting daripada bau. Bau hilang apabila tingkap dibuka. Minyak tidak: ia menjadi lapisan melekit di pintu kabinet, kesan kuning di siling dan kotoran dalam kipas yang sudah berjalan setahun. Hood dengan penapis minyak mengumpulkannya di satu tempat yang boleh anda bersihkan. Panduan kami tentang [cara membersihkan penapis minyak](/tips-tricks/how-to-clean-grease-filter/) menerangkan bahagian itu.

## Patutkah anda guna kedua-duanya?

Selalunya ya, dan ia paling berkesan mengikut urutan. Hidupkan hood sebelum mula memasak, supaya ia sudah menyedut apabila asap pertama naik, dan biarkan ia berjalan beberapa minit selepas itu. Gunakan exhaust fan untuk membuang haba dan kelembapan yang tinggal, atau untuk mengudarakan dapur selepas memasak lama. Hood menguruskan minyak; kipas menguruskan bilik.

Jika dapur anda sudah ada exhaust fan tetapi kabinet masih berminyak, itu tandanya kipas sedang melakukan kerja asalnya, dan asap itu memerlukan hood.

## Jika tiada dinding luar

Banyak dapur kondo terletak di tengah unit, tanpa dinding luar untuk kipas. Exhaust fan dinding tidak mungkin di situ, tetapi hood dapur masih boleh. Tiga belas hood VATTI menyenaraikan **ducted or recycled** pada helaian spesifikasinya, jadi ia boleh berfungsi dengan penapis karbon tanpa saluran. Tanpa saluran, tapisan minyak dan bunyi paling penting, jadi V959 (tapisan minyak 95%) dan [V929](/vatti-aetheris-series-cooker-hood-v929/) (46.5 dB) ialah pilihan paling kuat. Panduan kami tentang [hood dapur tanpa tebuk dinding](/ms/panduan-membeli/hood-dapur-tanpa-tebuk-dinding/) menerangkan apa yang berubah.

