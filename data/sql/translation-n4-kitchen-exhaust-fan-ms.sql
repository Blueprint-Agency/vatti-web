## Apa yang dilakukan oleh exhaust fan dapur

Exhaust fan dapur, atau kipas ekzos, ialah kipas pada dinding, tingkap atau siling yang menolak udara bilik ke luar. Ia bagus untuk kerja asalnya: menggantikan udara yang panas, lembap dan pengap dengan udara segar dari bahagian lain rumah. Untuk dapur yang terus panas lama selepas dapur gas ditutup, atau dapur basah di belakang dapur utama, ia memang berguna.

Apa yang ia tidak lakukan ialah menangkap asap di tempat asap itu bermula. Kipas biasanya agak jauh dari dapur gas, jadi asap dan wap minyak merebak ke seluruh bilik dalam perjalanan ke kipas. Apabila udara sampai ke bilah kipas, kebanyakan minyak sudah pun hinggap di kabinet, dapur dan siling. Dan kerana exhaust fan biasa tiada penapis minyak, minyak yang sampai ke kipas akan melekat pada bilahnya dan dinding di luar.

## Apa yang dilakukan oleh hood dapur

Hood dapur bekerja terus di sumbernya. Bukaan sedutannya duduk betul-betul di atas dapur gas, jadi ia menarik asap dan wap sebaik sahaja naik dari kuali, sebelum sempat merebak. Di dalamnya, penapis minyak menahan minyak: kebanyakan hood VATTI menapis 92% daripadanya, dan [V959](/vatti-cooker-hood-v959/) 95%. Yang keluar dari hood hanyalah udara, dihantar ke luar melalui saluran atau, pada hood tanpa saluran, dibersihkan melalui penapis karbon dan dikembalikan ke dapur.

Hood juga dibina untuk jumlah asap yang dihasilkan oleh kuali. Rangkaian VATTI menyedut antara 1,860 dan 3,690 m³/h, dan setiap model mampu membersihkan dapur biasa berkali-kali ganda. Panduan kami tentang [hood dapur terbaik](/ms/panduan-membeli/hood-dapur-terbaik/) menerangkan angka mana yang penting untuk dapur yang mana.

