## Infrared gas burner FAQs

**What is an infrared gas burner made of?**
A ceramic or perforated metal plate over a mixing chamber, with a thermocouple in the flame and a cast iron pan support above.

**Does an infrared gas burner need electricity?**
Only to make the spark. The heat is all gas. It works in a power cut.

