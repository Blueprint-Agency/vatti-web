On the open burner beside it, the same rules apply: blue is right, yellow means a blocked port or a wet cap.

## Why it uses less gas

With an open burner, the flames heat gas that then flows over the pan, and a good share of that hot gas misses the pan and rises around it. With a plate, the burner''s energy first heats the plate and then leaves it as radiation aimed at the pan base, and the hot gases still flow over the pan as well. More of the energy arrives at the pan, so the same cooking needs less gas. Manufacturers typically rate the saving at 10 to 20 percent, most of it at high heat, where an open burner wastes the most. Our guide to [whether an infrared gas stove is worth it](/buying-guide/is-an-infrared-gas-stove-worth-it/) puts that against the price.

## Why it stays lit in wind

The flame sits in and just above the ports rather than standing free in the air, so a draught cannot fold it over or blow it out. Kitchens with a window over the hob, a yard kitchen, or a ceiling fan running are where this is noticed first.

## How to clean an infrared gas burner

The plate is the only part that needs care, and the two rules are: never while it is hot, and never with anything that could block a port.

- **Let it cool completely.** A ceramic plate can crack if cold water or a wet cloth touches it while it glows. Wait until it is dark and cool to the hand.

- **Brush, do not scrub.** Use a soft dry brush, an old toothbrush or a soft nail brush, and sweep across the plate to clear ash, crumbs and burnt residue from the ports. Do not use a wire brush, a scouring pad or a knife point; they widen and damage the ports.

- **Lift a boil-over once it is dry.** Dried food comes off with the brush. If it is stubborn, a cloth wrung out in warm soapy water, used lightly on the surface and followed by thorough drying, is as wet as the plate should get.

- **Never pour water through it.** Water in the ports and the mixing chamber means yellow flame and sputtering until it has dried out, and on some burners it corrodes the chamber.

- **Clean the pan support separately.** Lift it off and wash it in the sink like any other support. See [cleaning stove grates](/tips-tricks/how-to-clean-stove-grates-a-step-by-step-guide/).

- **Refit the plate squarely.** A plate that sits loose or tilted burns unevenly and can lift the flame.

- **Do it monthly, and after any boil-over.** A plate kept clear lasts years. One left clogged burns yellow, wastes gas and eventually needs replacing.

## When to call for service

- The plate is cracked. Do not use the burner; a cracked plate can let flame through unevenly.

- The flame stays yellow after a thorough clean and drying. The air intake or the injector may be blocked.

- The burner will not light. Check the battery or the plug first; our guide to a [gas hob igniter that is not working](/tips-tricks/gas-hob-igniter-not-working/) covers the common causes.

- The plate has lost its even glow permanently. Ports have been damaged and the plate needs replacing, which is a service part from the brand.

