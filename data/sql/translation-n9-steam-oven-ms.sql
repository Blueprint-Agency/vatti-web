## Kenapa mengukus dalam ketuhar dan bukan kuali

- **Air tidak kering.** Ketuhar yang mengawal wap, jadi anda tidak perlu menambah air di tengah-tengah memasak.
- **Tiada air menitis.** Tiada tudung yang mengumpul wap di atas makanan, yang merosakkan telur kukus dan mencairkan kuah ikan. Ia tertulis pada helaian spesifikasi VA06 sebagai "no water dripping".
- **Lebih banyak serentak.** Ruang 70 L memuatkan beberapa dulang, jadi ikan, telur dan sayur boleh dikukus bersama.
- **Kuali bebas.** Semasa ikan dikukus, dapur bebas untuk menumis.
- **Mengukus pindah ke dapur kering.** Mengukus menghasilkan sedikit asap atau minyak, jadi ketuhar terbina dalam boleh diletakkan di dapur kering pada paras mata. Panduan kami tentang [dapur basah dan dapur kering](/ms/panduan-membeli/dapur-basah-dan-dapur-kering/) menerangkan peralatan mana diletakkan di mana.

## Wap dan haba kering bersama

Inilah yang ditambah ketuhar kombi berbanding ketuhar stim. **Stim-panggang** memanggang dengan wap di dalam ruang, jadi ayam rangup di luar dan berjus di dalam. **Stim-bakar** menambah wap pada minit-minit awal membakar, yang memberi roti kembangnya dan kerak yang rangup dan berkilat. VA06 menyenaraikan stim-panggang dan stim-bakar sebagai fungsi gabungan, dan VA05 menyenaraikan dua fungsi kombi.

## Apa yang perlu dilihat dalam ketuhar stim

- **Tahap wap.** Masakan yang berbeza memerlukan jumlah wap yang berbeza. Kedua-dua ketuhar kombi VATTI ada tiga: VA05 ada mod stim rendah, sederhana dan tinggi, dan VA06 ada tiga tahap kelembapan.
- **Kapasiti.** Keluarga yang mengukus beberapa masakan serentak memerlukan ruang untuk lebih daripada satu dulang. Kedua-dua model memuatkan 70 L.
- **Tangki air.** Ia menentukan berapa lama ketuhar boleh mengukus sebelum diisi semula. VA06 ada tangki 1.3 L.
- **Pembersihan dan penyahkerakan.** Wap meninggalkan air dan, lama-kelamaan, kerak. Kedua-dua model ada dua fungsi pembersihan automatik, cuci stim dan kering haba, jadi ruang ketuhar dibersihkan dan dikeringkan, bukan dibiarkan lembap.
- **Menu automatik.** Kedua-duanya ada 68 menu masakan automatik, cara paling mudah untuk mempelajari ketuhar pada minggu pertama.

