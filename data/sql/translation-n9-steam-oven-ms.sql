## Apa itu ketuhar stim?

Ketuhar stim ialah ketuhar tertutup dengan tangki air dan penjana wap. Anda isi tangki, pilih tahap wap dan tutup pintu. Ketuhar menukar air kepada wap dan memenuhkan seluruh ruang dengannya, jadi makanan dikelilingi wap dari setiap sisi, bukan duduk di atas periuk air mendidih.

Itulah bezanya dengan mengukus di atas dapur. Dalam kuali atau periuk kukus, haba datang dari bawah, paras air turun semasa memasak, dan wap terkumpul pada tudung lalu menitis semula ke atas makanan. Dalam ketuhar stim, ketuhar yang mengawal wap, dan tiada tudung untuk menitis.

