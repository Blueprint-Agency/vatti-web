## Soalan lazim ketuhar stim

**Adakah ketuhar stim sama dengan ketuhar kombi?**
Tidak. Ketuhar stim hanya mengukus. Ketuhar kombi mengukus, membakar dan memanggang dalam ruang yang sama, dan boleh menggunakan wap dan haba kering bersama. Setiap ketuhar VATTI dengan fungsi stim ialah ketuhar kombi.

**Bolehkah ketuhar stim menggantikan ketuhar gelombang mikro?**
Untuk memanaskan semula nasi, mi dan pau, wap memberi hasil yang lebih baik kerana makanan tidak kering. Ketuhar gelombang mikro lebih cepat, jadi banyak dapur menyimpan kedua-duanya.

**Bolehkah membakar dalam ketuhar stim?**
Tidak dalam ketuhar stim sahaja. Ketuhar kombi membakar seperti ketuhar biasa dan boleh menambah wap untuk roti dan panggang.

**Dari mana datangnya air?**
Dari tangki yang anda isi sebelum memasak. VA06 ada tangki 1.3 L.

**Bagaimana membersihkan ketuhar stim?**
Lap ruang ketuhar selepas ia sejuk dan biarkan kering. Kedua-dua ketuhar kombi VATTI ada fungsi cuci stim yang melonggarkan minyak dan fungsi kering haba yang mengeluarkan kelembapan selepas itu.

