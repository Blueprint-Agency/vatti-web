## 厨房抽风机的作用

厨房抽风机（也叫排风扇）是装在墙上、窗口或天花板的风扇，把室内空气推到外面。它做好本分很称职：把闷热、潮湿、不新鲜的空气换成屋内其他地方的新鲜空气。关火后还热很久的厨房，或主厨房后面的湿厨房，有一台抽风机是好事。

它做不到的，是在油烟产生的地方把它接住。抽风机通常离炉头有一段距离，油烟和油雾在飘向它的途中已经散满整个厨房。等空气到达扇叶时，大部分油已经落在橱柜、炉台和天花板上。而一般的抽风机没有油网，真正到达风扇的那些油，就黏在扇叶和外墙上。

## 抽油烟机的作用

抽油烟机直接在源头工作。进风口就在炉头正上方，油烟和蒸汽一从锅里升起就被吸上去，来不及扩散。机身里的油网会把油留住：大部分 VATTI 抽油烟机的油脂分离率是 92%，[V959](/vatti-cooker-hood-v959/) 达 95%。离开抽油烟机的只是空气，经排烟管排到室外；不接排烟管时，则经过活性炭滤网净化后回到厨房。

它也是为炒锅的油烟量而设计的。VATTI 系列的风量在 1,860 到 3,690 m³/h 之间，每一款都能把普通厨房的空气换好几遍。我们的[抽油烟机推荐](/zh/buying-guide/best-kitchen-hood-malaysia/)说明哪些数字对哪种厨房最重要。

