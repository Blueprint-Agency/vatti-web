## 为什么炒锅煮食一定要有抽油烟机

马来西亚式煮食几分钟产生的油烟和油雾，比很多地方的厨房一整晚还多。猛火爆炒时，油雾往上冲得又快又散。厨房另一头的抽风机来不及把它横向拉走；抽油烟机就在锅子上方不远处，正好挡在油烟的路线上。

油比气味更要紧。气味开窗就散，油不会：它变成橱柜门上黏黏的一层、天花板上的黄渍，还有用了一年的风扇里那层油垢。有油网的抽油烟机把油集中在一个可以清洗的地方。我们的[油网清洗指南](/tips-tricks/how-to-clean-grease-filter/)讲的就是这一步。

## 两个一起用好吗？

通常是好的，而且按顺序用效果最好。开火之前先开抽油烟机，第一缕油烟升起时它已经在吸；煮完后再让它多运转几分钟。剩下的热气和湿气，或者长时间煮食后的闷气，就交给抽风机。抽油烟机管油烟，抽风机管整个空间。

如果你的厨房已经有抽风机，橱柜却还是油腻腻的，就说明抽风机只是在做它本来的工作，那些油烟需要的是抽油烟机。

## 厨房没有外墙怎么办

很多公寓的厨房在单位中间，没有外墙可以开抽风机。墙上的抽风机行不通，但抽油烟机仍然可以。VATTI 有 13 款抽油烟机的规格表注明 **ducted or recycled**，可以只用活性炭滤网、不接排烟管。不接排烟管时，油脂分离率和噪音最重要，所以 V959（油脂分离率 95%）和 [V929](/vatti-aetheris-series-cooker-hood-v929/)（46.5 dB）是最好的选择。我们的[免打孔抽油烟机指南](/zh/buying-guide/which-is-better-ducted-or-ductless-range-hood/)说明有什么不同。

