## 为什么蒸蛋糕特别湿润

烤箱里的干热会让蛋糕结皮，把水分逼出来。在蒸汽里，蛋糕四周的空气充满水分，外层不会干，里面从头到尾都又软又湿。巧克力蒸蛋糕的面糊本来就很稀：液体多，用油不用牛油，再加小苏打和泡打粉，让它在蒸汽里膨起来又不会变干。

## 为什么用蒸烤箱蒸

传统做法是在炉头上用大蒸锅，锅盖包一条布，免得水滴落在蛋糕上，留下坑洞、变得湿烂。将近一个小时都要保持大滚，还要中途加滚水。

蒸烤箱帮你做了这些。蒸汽均匀充满箱体，由箱体控制，不会烧干，也没有会滴水的锅盖。两款 VATTI 华帝蒸烤箱都能蒸：[VA05](/built-in-combi-oven-va05/) 有低、中、高三种蒸汽模式，[VA06](/vatti-magic-series-combi-oven-va06/) 有三种蒸汽模式，规格表上写明“no water dripping”（不滴水）。用最高档。我们的[蒸烤箱有必要买吗](/zh/buying-guide/what-is-a-steam-oven/)指南说明它还能做什么。

## 蒸出湿润均匀蛋糕的诀窍

- **鸡蛋和牛奶用室温的。**冷的液体会让面糊凝固得不均匀。
- **用汤匙把面粉舀进量杯。**直接用量杯挖会把面粉压实，分量过多，蛋糕就又干又重。
- **拌到刚好均匀就停。**加了面粉后拌过头，蛋糕会变韧。有几个小颗粒没关系。
- **震一震模具。**在桌上轻轻震两三下，把大气泡震出来。
- **别太早开门。**头 30 分钟让蒸汽跑掉，是蒸蛋糕塌陷最常见的原因。

## 美禄版本

做美禄蒸蛋糕，把 1/2 杯可可粉换成 1/4 杯可可粉加 1/2 杯美禄，糖减到 3/4 杯，因为美禄本身已经甜。蛋糕颜色较浅，带麦芽香，其他照旧。

## 巧克力酱（ganache）

蛋糕完全凉透才淋酱，不然酱会滑下来、渗进蛋糕里。把鲜奶油加热到冒烟，倒在切碎的巧克力上，等两分钟，从中间开始拌到光亮，再拌入牛油。淋好后放冰箱冷藏 30 分钟让表面凝固。很多马来西亚人喜欢冰冰的直接吃。

## 巧克力蒸蛋糕常见问题

**为什么我的蒸蛋糕会塌？**
通常是太早开门或开盖、一开始蒸汽不够强，或是膨松剂放太多。放模具进去前先用最大蒸汽预热，头 30 分钟别打开。

**为什么我的蒸蛋糕又硬又实？**
面粉太多（直接用量杯挖而不是用汤匙舀），或加面粉后拌过头。拌到刚好均匀就好。

**巧克力蛋糕要蒸多久？**
20 厘米圆模用最大蒸汽大约蒸 45 至 50 分钟，杯子蛋糕 15 至 20 分钟。用竹签插中间测试。

**这个蛋糕可以用烤的吗？**
可以，用大约 170°C 烤 40 至 45 分钟。表面会比较硬，口感也没有蒸的那么湿润。

**巧克力蒸蛋糕可以放多久？**
加盖放冰箱，最多四天。喜欢软一点的话，吃前 15 分钟拿出来。

