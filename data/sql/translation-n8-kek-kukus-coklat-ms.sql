## Tip untuk kek yang lembap dan sekata

- **Telur dan susu pada suhu bilik.** Cecair sejuk menjadikan adunan masak tidak sekata.
- **Sudukan tepung ke dalam cawan.** Mencedok terus memadatkannya dan memberi terlalu banyak tepung, yang menjadikan kek kering dan berat.
- **Gaul sehingga sebati sahaja.** Terlebih gaul selepas tepung dimasukkan menjadikan kek liat. Sedikit ketulan kecil tidak mengapa.
- **Hentak loyang.** Hentak perlahan di atas meja dua atau tiga kali untuk mengeluarkan gelembung udara besar.
- **Jangan buka pintu terlalu awal.** Membiarkan wap keluar dalam 30 minit pertama ialah sebab biasa kek kukus mendap.

## Versi kek kukus Milo

Untuk kek kukus Milo, gunakan 1/4 cawan serbuk koko dan 1/2 cawan Milo sebagai ganti 1/2 cawan koko, dan kurangkan gula kepada 3/4 cawan, kerana Milo sudah manis. Kek lebih cerah warnanya dan berperisa malt. Yang lain kekal sama.

## Topping coklat (ganache)

Tuang topping hanya apabila kek benar-benar sejuk, jika tidak ia akan meleleh dan meresap ke dalam kek. Panaskan krim sehingga berwap, tuang ke atas coklat yang dicincang, tunggu dua minit dan kacau dari tengah sehingga berkilat, kemudian masukkan mentega. Sejukkan kek dalam peti sejuk selama 30 minit supaya topping set. Ramai orang Malaysia menghidangkannya terus dari peti sejuk.

## Soalan lazim kek kukus coklat

**Kenapa kek kukus saya mendap?**
Biasanya kerana pintu atau tudung dibuka terlalu awal, wap tidak cukup kuat dari mula, atau terlalu banyak bahan penaik. Panaskan dahulu pada wap penuh sebelum loyang dimasukkan, dan jangan buka dalam 30 minit pertama.

**Kenapa kek kukus saya keras atau padat?**
Terlalu banyak tepung, kerana dicedok terus dan bukan disudukan ke dalam cawan, atau terlebih gaul selepas tepung dimasukkan. Gaul sehingga sebati sahaja.

**Berapa lama mengukus kek coklat?**
Kira-kira 45 hingga 50 minit untuk loyang bulat 20 cm pada wap penuh. Kek cawan mengambil 15 hingga 20 minit. Uji dengan lidi di tengah.

**Bolehkah kek ini dibakar?**
Boleh. Bakar pada kira-kira 170°C selama 40 hingga 45 minit. Bahagian atasnya lebih keras dan isinya kurang sedikit lembap berbanding versi kukus.

**Berapa lama kek kukus coklat tahan?**
Sehingga empat hari dalam peti sejuk dalam bekas bertutup. Keluarkan 15 minit sebelum dihidang jika anda suka lebih lembut.

