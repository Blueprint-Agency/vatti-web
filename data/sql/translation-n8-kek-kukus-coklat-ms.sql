## Kenapa kek kukus kekal lembap

Dalam ketuhar biasa, haba kering membentuk kerak dan mengeluarkan air dari kek. Dalam wap, udara di sekeliling kek penuh kelembapan, jadi bahagian luar tidak kering dan isinya kekal lembut dan lembap sepenuhnya. Adunan kek kukus memang cair: banyak cecair, minyak dan bukan mentega, serta soda bikarbonat dan serbuk penaik, supaya ia naik dalam wap tanpa menjadi kering.

## Kenapa kukus dalam ketuhar stim

Cara biasa ialah pengukus besar di atas dapur, dengan tudung dibalut kain supaya titisan air tidak jatuh ke atas kek dan meninggalkan lubang dan bahagian lembik. Air perlu terus mendidih hampir sejam dan ditambah dengan air panas.

Ketuhar stim melakukan kerja itu untuk anda. Wap memenuhi ruang dengan sekata, ketuhar mengawalnya supaya air tidak kering, dan tiada tudung yang menitis ke atas kek. Kedua-dua ketuhar kombi VATTI boleh mengukus: [VA05](/built-in-combi-oven-va05/) ada mod stim rendah, sederhana dan tinggi, dan [VA06](/vatti-magic-series-combi-oven-va06/) ada tiga mod mengukus dan menyenaraikan "no water dripping" pada helaian spesifikasinya. Gunakan tetapan paling tinggi. Panduan kami tentang [apa itu ketuhar stim](/ms/panduan-membeli/apa-itu-ketuhar-stim/) menerangkan apa lagi yang boleh dimasak.

