## 港式清蒸鱼

港式做法重在鱼本身：蒸的时间短，倒掉蒸出来的水，再铺上新鲜姜丝和葱丝，淋热油和清淡的豉油汁。材料和步骤在下面第一张食谱卡里。

三个关键：

- **倒掉蒸鱼水。**腥味都在那里，加酱汁前先倒掉。
- **新鲜的香料放上面。**鱼垫着老姜和葱段蒸，蒸好后丢掉，再铺上新切的姜丝、葱丝。
- **热油要够热。**油烧到冒烟前，淋在姜丝和葱丝上，“滋”一声，香味就出来了。

## 马来酸柑蒸鱼

马来酸柑蒸鱼（ikan stim limau）又酸又辣：鱼和香茅、姜一起蒸，再淋上用青柠汁、蒜末、小辣椒和鱼露煮成的热汤汁。它和泰式青柠蒸鱼很接近，做法也一样。材料和步骤在下面第二张食谱卡里。

