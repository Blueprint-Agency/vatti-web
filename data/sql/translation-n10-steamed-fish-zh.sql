## 蒸鱼常见问题

**鱼要蒸多久？**
600 至 700 克的整条鱼，用最大蒸汽蒸大约 10 至 12 分钟；鱼片或鲳鱼这类薄身的鱼，6 至 8 分钟。看靠近鱼头最厚的部位：鱼肉要全白，一拨就离骨。

**没有蒸笼可以蒸鱼吗？**
可以。用炒锅的话，把碟子架在滚水上方的蒸架上，盖好大火蒸。用蒸烤箱的话，把碟子放在托盘上，用最高的蒸汽档。

**为什么我的蒸鱼有腥味？**
通常是因为蒸鱼水一起上桌了。把它倒掉，鱼下面垫姜和葱再蒸。最重要的还是鱼要新鲜。

**冷冻鱼可以直接蒸吗？**
先放冰箱解冻，再抹干。直接从冷冻状态蒸，外面会过熟，中间还没熟。

**哪种鱼最适合清蒸？**
金目鲈最常见。红鱼和石斑肉更结实、更鲜甜；鲳鱼较薄，熟得较快。

