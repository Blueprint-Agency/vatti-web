## 怎么选鱼

肉质结实的白肉鱼都适合。**金目鲈**（siakap）是马来西亚最常见的选择，大部分餐馆也用它。**红鱼**和**石斑**肉更结实、更鲜甜；**鲳鱼**较薄，熟得快一两分钟。请鱼贩帮你去鳞去肚。新鲜的鱼眼睛清亮、鱼鳃鲜红，按下去鱼肉会弹回来。

鱼身最厚处超过 3 厘米的话，在两面各斜切两三刀，切到骨头。蒸汽更快进到中间，厚的部位和鱼尾就能同时熟。

## 为什么用蒸烤箱蒸

在炉头上蒸，鱼放在滚水上、盖上锅盖。热从下面来，水可能烧干，锅盖上的水汽滴到鱼身上，把汁冲淡。用蒸烤箱，蒸汽充满整个箱体，鱼四面受热均匀，也没有水滴下来。你还可以在另一层托盘同时蒸饭和蔬菜。

