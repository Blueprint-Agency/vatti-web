## 金针菇的处理

金针菇是真空包装，底部根部连成一块。切掉底部2至3厘米，把菇撕成小束，让蒸汽和酱汁能渗进每一根。用冷水快速冲洗后沥干。金针菇一定要洗净煮熟，不可生吃。

把小束金针菇平铺在有边的浅口耐热盘上。盘边很重要：酱汁和金针菇蒸出的水会留在盘里，成为最后的汤汁。

![把蒜蓉、指天椒和葱花铺在白盘里的生金针菇上。](https://cdn.vattimalaysia.com/2023/11/step4_spicy-enoki-mushroom.webp)

## 用蒸烤箱蒸金针菇

在蒸烤箱里，蒸汽均匀包围整个盘子，也不会有水滴落在菜上，所以金针菇能平铺一层均匀蒸熟，不会变得水汪汪。用最高蒸汽档蒸6至8分钟。金针菇很细，容易蒸过头：超过10分钟就会变得软滑、失去口感。

两款 VATTI 蒸烤一体机都能蒸：[VA05](/built-in-combi-oven-va05/) 有低、中、高三档蒸汽，[VA06](/vatti-magic-series-combi-oven-va06/) 有三种蒸汽模式。可以同时在另一层蒸鱼或蒸饭。想了解蒸烤箱的原理，可以看我们的[蒸烤箱是什么](/zh/buying-guide/what-is-a-steam-oven/)。

