## 酱汁与热油

酱汁在蒸之前淋上，让金针菇一边蒸一边吸味；热油在蒸好之后浇上，激出生蒜和辣椒的香气。

![在铺好蒜蓉和辣椒的金针菇上淋生抽蚝油汁，准备入锅蒸。](https://cdn.vattimalaysia.com/2023/11/step9_spicy-enoki-mushroom.webp)

- **蚝油和生抽**提供咸鲜味。
- **少许糖**让酱油味更圆润。
- **麻油**放进酱汁里，不要放进热油：高温会让它变苦。
- **辣椒油**可加可不加。不加的话，味道偏蒜香而不是麻辣。

## 搭配建议

- **白饭或清汤面**，把盘里的酱汁也拌进去。
- **清蒸鱼或豆腐**，用同一台蒸烤箱在另一层一起蒸。
- **火锅**，作为现成的调味配菜。
- **清炒青菜**，如芥兰或小白菜。

## 蒸金针菇常见问题

**金针菇要蒸多久？**
用最高蒸汽蒸6至8分钟，蒸烤箱或加盖炒锅隔水蒸都一样。菇身变软但还有一点脆度就是熟了。

**金针菇需要洗吗？**
需要。切掉根部，把菇撕开，用冷水快速冲洗后沥干。金针菇一定要煮熟才能吃。

**金针菇可以用烤箱或气炸锅做吗？**
可以，但口感不同。干热会把菇尖烤脆、把菇身烤干；蒸汽能保持滑嫩，也更容易吸收酱汁。这道菜建议用蒸的。

**金针菇能放多久？**
未开封放冰箱大约一周。开封后用厨房纸包好放进保鲜盒，两三天内吃完。变褐或发黏就要丢掉。

**金针菇是低碳水的食物吗？**
是的。金针菇主要是水分和膳食纤维，热量和碳水都低。

