## 蒸箱常见问题

**蒸箱和蒸烤箱一样吗？**
不一样。蒸箱只能蒸。蒸烤箱在同一个箱体里能蒸、能烘焙、能烤，还能蒸汽与干热一起用。VATTI 华帝所有带蒸功能的烤箱都是蒸烤箱。

**蒸箱能代替微波炉吗？**
翻热米饭、面和包子，蒸汽的效果更好，因为食物不会变干。微波炉比较快，所以很多厨房两样都有。

**蒸箱能烘焙吗？**
纯蒸箱不能。蒸烤箱可以像普通烤箱一样烘焙，做面包和烤肉时还能加入蒸汽。

**水从哪里来？**
从煮之前加满的水箱来。VA06 的水箱是 1.3 L。

**蒸箱怎么清洁？**
等箱体冷却后擦干净，让它晾干。两款 VATTI 华帝蒸烤箱都有蒸汽清洁功能软化油污，再用高温烘干功能把湿气带走。

