## 蒸箱在马来西亚厨房能做什么

### 蒸鱼

最能让人爱上蒸箱的就是蒸鱼。蒸汽从四面来，一整条鱼从头到尾熟得均匀，靠近鱼头的厚肉熟了，鱼尾还是嫩的。广东式的豉油、姜丝、葱，或马来式的酸柑辣椒，开头都一样：鱼放碟上，碟放托盘上，剩下的交给蒸汽。

### 蒸蛋

蒸蛋要滑，靠的是温和稳定的火力，以及表面不能有水滴下来。较低的蒸汽档位加上密闭的箱体，两样都做到了，蒸出来的表面才会像镜面一样，而不是满是蜂窝。

### 包子、点心和娘惹糕

包子、烧卖、虾饺、kuih seri muka、kuih talam 和蒸蛋糕，都要在固定时间里有均匀的蒸汽。一个箱体放几层托盘，一整批一起蒸好，不必用叠起来的蒸笼一轮一轮地蒸，下层也不会在等上层的时候蒸过头。

### 米饭和糯米饭

两款 VATTI 华帝蒸烤箱都有蒸饭功能。做糯米鸡的糯米饭，或电饭锅正在用时的白饭，都可以放托盘上蒸。

### 蔬菜和翻热

蒸出来的蔬菜颜色鲜、口感脆。翻热剩菜时，蒸汽能让米饭、面和包子恢复原样，不会像微波炉那样边缘变硬，只是时间长一些。要快速翻热，[嵌入式微波炉](/built-in-microwave-m626/)还是更快。

