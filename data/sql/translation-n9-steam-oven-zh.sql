## 蒸箱是什么？

蒸箱是带水箱和蒸汽发生器的密闭箱体。加满水箱，选好蒸汽档位，关上门，蒸箱就把水变成蒸汽，充满整个箱体，食物四面都被蒸汽包围，而不是架在一锅滚水上面。

这就是和在炉头上蒸的分别。用炒锅或蒸锅，热从下面来，水位会越煮越低，锅盖上积起的水汽又滴回食物上。用蒸箱，蒸汽由箱体控制，也没有会滴水的锅盖。

