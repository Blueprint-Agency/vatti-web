## 为什么用蒸箱蒸，而不是炒锅

- **不会烧干。**蒸汽由箱体控制，不必蒸到一半去加水。
- **没有滴水。**食物上方没有积水的锅盖，蒸蛋不会被滴坏，蒸鱼的汁也不会被冲淡。VA06 的规格表上写明“no water dripping”（不滴水）。
- **一次蒸更多。**70 L 的箱体放得下几层托盘，鱼、蛋和蔬菜可以一起蒸。
- **炒锅空出来。**鱼在蒸的时候，炉头可以拿来炒菜。
- **蒸煮可以移到干厨房。**蒸煮几乎没有油烟，嵌入式烤箱可以装在干厨房、与视线齐平的位置。我们的[干湿厨房指南](/zh/buying-guide/wet-kitchen-vs-dry-kitchen/)说明了每种电器该放哪里。

## 蒸汽和干热一起用

这就是蒸烤箱比蒸箱多出来的部分。**蒸汽烧烤**在烤的同时箱体里有蒸汽，鸡外皮烤脆、里面多汁。**蒸汽烘焙**在烘焙的前几分钟加入蒸汽，面包因此膨得起来，外皮又脆又亮。VA06 把蒸汽烧烤和蒸汽烘焙列为复合功能，VA05 则列有两种复合功能。

## 挑选蒸箱要看什么

- **蒸汽档位。**不同的菜需要的蒸汽量不同。两款 VATTI 华帝蒸烤箱都有三档：VA05 有低、中、高三种蒸汽模式，VA06 有三档湿度。
- **容量。**一家人同时蒸几道菜，需要放得下不止一层托盘。两款都是 70 L。
- **水箱。**它决定加一次水能蒸多久。VA06 的水箱是 1.3 L。
- **清洁和除垢。**蒸汽会留下水分，久了还会积水垢。两款都有两种自动清洁功能：蒸汽清洁和高温烘干，箱体会被清洁并烘干，而不是一直潮湿。
- **自动菜单。**两款都有 68 道自动烹饪菜单，是第一周上手最简单的方法。

