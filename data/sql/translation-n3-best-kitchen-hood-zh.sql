## 常见问题

**马来西亚公寓用哪种抽油烟机最好？**
选静压高的。公寓的烟管长、有转弯，又是共用的，最好选 1,000 Pa 以上。VATTI 系列中最强的是 V960（1,700 Pa）和 V938（1,600 Pa）。

**油烟机哪个牌子好？**
比起牌子，更关键的是厨房：烟管多长、厨房是否开放、多常爆炒。选对风量、静压和噪音，才是真正适合你的抽油烟机。VATTI 每款型号都列出同样的实测数字，方便直接比较。

**最安静的抽油烟机是哪一款？**
VATTI 系列中是 V929，只有 46.5 dB，风量仍有 3,125 m³/h。

**马来西亚厨房需要多大风量？**
一般厨房约 650 至 800 m³/h，就能每小时换气十次，而每款 VATTI 抽油烟机都远高于此。天天炒锅猛火煮食和开放式厨房，才是大风量真正派上用场的地方。

**免打孔抽油烟机够用吗？**
煮食清淡的话，够用。天天猛火爆炒就最好接排烟管，因为内循环油烟机会把热气和水汽送回厨房。有 13 款 VATTI 抽油烟机两种方式都适用。

**T 型还是升降式抽油烟机好？**
T 型是经典的平板机身加烟囱；升降式把吸烟口降到更靠近锅具的位置，油烟一冒起就被吸走。两者的比较请看[抽油烟机怎么选](/zh/buying-guide/types-of-range-hoods/)。

