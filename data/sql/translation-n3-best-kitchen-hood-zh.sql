## 怎样的抽油烟机才适合马来西亚厨房

马来西亚人的煮食方式对抽油烟机要求很高。爆炒、炒参巴、油炸，几分钟产生的油烟和油雾，比烤箱烤一小时还多，所以为西式厨房设计的油烟机，在这里常常力不从心。一台抽油烟机跟不跟得上，看以下四点。

**风量（m³/h）。** 抽油烟机每小时能抽走多少空气。VATTI 系列的风量由 1,860 m³/h 到 3,690 m³/h，每一款都足以应付一般厨房。开放式厨房最需要大风量，因为油烟会扩散到整个空间。

**静压（Pa）。** 抽油烟机把空气推过烟管阻力的能力。公寓最需要看这个数字：烟管长、有转弯，还和楼上楼下的单位共用。VATTI 系列的静压由 420 Pa 到 1,700 Pa。

**噪音（dB）。** 太吵的抽油烟机，往往油烟还没散就被关掉了。VATTI 系列的噪音由 46.5 dB 到 54 dB，每相差 3 dB，耳朵就听得出分别。

**油脂分离率（%）。** 抽油烟机能把多少油脂留在机内，而不是排进烟管或沾上橱柜。大部分 VATTI 抽油烟机为 92%，V959 则达 95%。

