## Memilih ikan

Mana-mana ikan isi putih yang pejal sesuai. **Siakap** ialah pilihan paling biasa di Malaysia dan yang digunakan kebanyakan restoran. **Ikan merah** dan **kerapu** lebih pejal dan manis; **bawal** lebih nipis dan masak beberapa minit lebih cepat. Minta penjual ikan membuang sisik dan perutnya. Ikan segar matanya jernih, insangnya merah dan isinya melantun semula apabila ditekan.

Untuk ikan yang lebih tebal daripada 3 cm di bahagian paling tebal, toreh dua atau tiga kali secara serong di setiap sisi hingga ke tulang. Wap sampai ke tengah lebih cepat, dan bahagian tebal masak serentak dengan ekornya.

## Kenapa mengukus dalam ketuhar stim

Di atas dapur, ikan dikukus di atas air mendidih dengan tudung tertutup. Haba datang dari bawah, air boleh kering, dan wap yang terkumpul menitis dari tudung ke atas ikan lalu mencairkan kuahnya. Dalam ketuhar stim, wap memenuhi seluruh ruang, jadi ikan masak sekata dari setiap sisi dan tiada apa yang menitis. Anda juga boleh mengukus nasi dan sayur di dulang kedua pada masa yang sama.

Kedua-dua ketuhar kombi VATTI boleh mengukus: [VA05](/built-in-combi-oven-va05/) ada mod stim rendah, sederhana dan tinggi, dan [VA06](/vatti-magic-series-combi-oven-va06/) ada tiga mod mengukus dan tangki air 1.3 L. Gunakan tetapan paling tinggi untuk ikan. Panduan kami tentang [apa itu ketuhar stim](/ms/panduan-membeli/apa-itu-ketuhar-stim/) menerangkan cara ia berfungsi dan apa lagi yang boleh dimasak.

## Ikan stim limau

Ikan stim limau masam dan pedas: ikan dikukus bersama serai dan halia, kemudian disiram kuah panas air limau nipis, bawang putih, cili padi dan sos ikan. Ia hampir sama dengan ikan stim limau gaya Thai, dan caranya sama. Bahan dan langkahnya ada dalam kad resepi pertama di bawah.

Masukkan air limau selepas api ditutup. Air limau yang mendidih menjadi pahit, jadi panaskan kuah dahulu dan perah limau ke dalamnya sejurus sebelum dituang.

## Ikan stim halia gaya Cina

Gaya Cina menumpukan pada ikan itu sendiri: dikukus sekejap, air kukusan dibuang, kemudian halia muda dan daun bawang segar, minyak panas dan kuah kicap yang ringan. Bahan dan langkahnya ada dalam kad resepi kedua di bawah.

