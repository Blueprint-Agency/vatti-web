Tiga perkara yang membezakannya:

- **Buang air kukusan.** Air itu membawa bau hanyir. Tuang keluar sebelum menambah kuah.
- **Bahan aromatik segar di atas.** Kukus ikan di atas halia tua dan daun bawang, kemudian buang dan tabur hirisan segar di atasnya.
- **Desiskan minyak.** Panaskan minyak hingga berkilat dan tuang ke atas halia dan daun bawang. Itulah yang mengeluarkan wanginya.

## Soalan lazim ikan stim

**Berapa lama mengukus ikan?**
Kira-kira 10 hingga 12 minit untuk seekor ikan 600 hingga 700 g pada wap penuh, dan 6 hingga 8 minit untuk filet atau ikan nipis seperti bawal. Periksa bahagian paling tebal dekat kepala: isinya patut putih sepenuhnya dan tertanggal dari tulang.

**Bolehkah mengukus ikan tanpa pengukus?**
Boleh. Dalam kuali, letakkan pinggan di atas rak di atas air mendidih, tutup dan kukus dengan api besar. Dalam ketuhar stim, letakkan pinggan di atas dulang dan gunakan tetapan wap paling tinggi.

**Kenapa ikan stim saya berbau hanyir?**
Biasanya kerana air kukusan dihidangkan bersamanya. Buang air itu, dan kukus ikan di atas halia dan serai atau daun bawang. Ikan yang segar paling penting.

**Bolehkah mengukus ikan beku?**
Cairkan dalam peti sejuk dahulu dan keringkan. Mengukus dari beku menjadikan bahagian luar terlebih masak sebelum bahagian tengah masak.

**Ikan apa paling sesuai untuk dikukus?**
Siakap paling biasa. Ikan merah dan kerapu lebih pejal dan manis; bawal lebih nipis dan lebih cepat masak.

