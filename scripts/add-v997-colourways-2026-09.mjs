// V997's two unshot colourways -> old-media/2026/09 webp keys, and the SQL that
// wires them in as same-page colour swatches.
//
//   node scripts/add-v997-colourways-2026-09.mjs
//   pnpm media:upload
//
// Background. The 2026-08 shoot folder holds three V997 colourways — Black, AG
// Grey and White — and generate-product-images-2026-08.mjs mapped only Black,
// because V997 was one product with no colour_variant. The 2026 catalogue (p.08)
// prices all three: Dark Black RM3,399, AG Grey RM3,699, Pearl White RM3,699.
//
// These do NOT become products. V917 and DWID3 model a colourway as a sibling
// product sharing variant_group, which is right for them (V917 has two legacy
// URLs that must both resolve, DWID3 was shipped that way), but wrong here: it
// would put three near-identical copies of V997's specs, features and FAQ on
// three URLs, and /vatti-range-hood-v997/ is the one that carries the traffic.
// So the colours are swatches on the single existing page — see the
// product_colourway table added in schema.sql.
//
// C836G is not in this script. Its AG Grey shot was already uploaded in the
// 2026-08 batch as a nondescript "detail view" gallery image; it only needs
// relabelling, which the SQL file does directly.
//
// Read-only against .data/vatti.db. Writes files and one SQL file; db:build
// re-runs the SQL.
import { mkdirSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import path from "node:path";
import sharp from "sharp";
import { CDN } from "./cdn.mjs";

const ROOT = path.join(import.meta.dirname, "..");
const SRC = "C:/Users/danie/Downloads/vatti product images/Vatti Product Image";
const SQL_OUT = path.join(ROOT, "data/sql/product-swatches-2026-09.sql");

// Catalogue names, not folder names. The folders say "Black"/"White"; the 2026
// catalogue sells them as Dark Black and Pearl White, and that is what a buyer
// asks a dealer for. AG Grey is the same in both.
const COLOURWAYS = [
  {
    folder: "Cooker Hood/V997 (AG Grey)",
    name: "AG Grey",
    keyBase: "vatti-range-hood-v997-ag-grey",
  },
  {
    folder: "Cooker Hood/V997 (White)",
    name: "Pearl White",
    keyBase: "vatti-range-hood-v997-pearl-white",
  },
];

// The shots each colourway folder carries, in the order they should appear.
const SHOTS = [
  { file: "F.png", suffix: "front", label: "front view", swatch: true },
  { file: "QF.png", suffix: "quarter-front", label: "angled view", swatch: false },
  { file: "S.png", suffix: "side", label: "side view", swatch: false },
];

const db = new DatabaseSync(path.join(ROOT, ".data/vatti.db"), { readOnly: true });
const product = db.prepare("SELECT id, name FROM product WHERE slug = ?").get("vatti-range-hood-v997");
if (!product) throw new Error("vatti-range-hood-v997 not in the database — run db:build first");

const maxImageId = db.prepare("SELECT max(id) AS m FROM image").get().m;
const maxPosition = db.prepare(
  "SELECT max(position) AS m FROM product_image WHERE product_id = ?"
).get(product.id).m;

let nextImageId = maxImageId + 1;
let nextPosition = maxPosition + 1;

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const imageLines = [];
const productImageLines = [];
const colourwayLines = [];

for (const [i, colour] of COLOURWAYS.entries()) {
  for (const shot of SHOTS) {
    const key = `2026/09/${colour.keyBase}-${shot.suffix}.webp`;
    const dest = path.join(ROOT, "old-media", key);
    mkdirSync(path.dirname(dest), { recursive: true });

    await sharp(path.join(SRC, colour.folder, shot.file)).webp({ quality: 90, effort: 6 }).toFile(dest);
    const meta = await sharp(dest).metadata();

    const id = nextImageId++;
    const alt = `${product.name} in ${colour.name}, ${shot.label}`;
    imageLines.push(
      `INSERT INTO image (id, url, legacy_url, alt, width, height) VALUES (${id}, ${q(CDN + "/" + key)}, NULL, ${q(alt)}, ${meta.width}, ${meta.height});`
    );
    productImageLines.push(
      `INSERT INTO product_image (product_id, image_id, position, role) VALUES (${product.id}, ${id}, ${nextPosition++}, 'gallery');`
    );
    if (shot.swatch) {
      // position 2 and 3 — Dark Black is 1, written by hand in the SQL file
      // because its image already exists from the 2026-08 batch.
      colourwayLines.push(
        `INSERT INTO product_colourway (product_id, position, name, image_id) VALUES (${product.id}, ${i + 2}, ${q(colour.name)}, ${id});`
      );
    }
    console.log(`  ${key}  ${meta.width}x${meta.height}`);
  }
}

const sql = `-- GENERATED by scripts/add-v997-colourways-2026-09.mjs, then extended by hand
-- for C836G (see the foot of the file). Regenerate the V997 half with:
--   node scripts/add-v997-colourways-2026-09.mjs
--
-- The filename is load-bearing, the same way product-outline-dimensions-* is.
-- db-build.mjs loads non-ORDER files alphabetically and this one reuses image
-- ids 9023, 9050 and 9051 from product-images-2026-08.sql, so it has to sort
-- after it: "product-s" > "product-i". Called product-colourways-* it loads
-- first and fails on a foreign key.
--
-- V997's AG Grey and Pearl White colourways, from the 2026-08 shoot folder that
-- the first import only took Black from. The 2026 catalogue p.08 sells all three.
--
-- These are swatches on the existing page, not sibling products: V917 and DWID3
-- use variant_group because they have to, and copying that here would put three
-- near-identical pages on three URLs and split the traffic /vatti-range-hood-v997/
-- already earns. See product_colourway in schema.sql.

${imageLines.join("\n")}

${productImageLines.join("\n")}

-- Dark Black is the colourway the page already showed. Its front shot is image
-- 9023, uploaded in the 2026-08 batch and still the product hero, so it is
-- reused rather than re-uploaded under a second key. Its three shots were named
-- before there was a second finish to tell them apart from, so they say which
-- one they are now that the gallery holds all three.
UPDATE image SET alt = 'Range Hood V997 in Dark Black, front view'   WHERE id = 9023;
UPDATE image SET alt = 'Range Hood V997 in Dark Black, angled view'  WHERE id = 9024;
UPDATE image SET alt = 'Range Hood V997 in Dark Black, side view'    WHERE id = 9025;

INSERT INTO product_colourway (product_id, position, name, image_id) VALUES (${product.id}, 1, 'Dark Black', 9023);
${colourwayLines.join("\n")}

-- ── C836G ───────────────────────────────────────────────────────────────────
-- Catalogue p.11 sells the C836G in AG Grey and Black. Both shots were already
-- uploaded in 2026-08: the folder is named "C836 (AG Grey)" but its F.png is the
-- BLACK hob, and the AG Grey one is the separately named file, which landed as a
-- "detail view" gallery image. Nothing new to upload, only the labels are wrong.
UPDATE image SET alt = 'VATTI Flexi Hob C836G in Black, front view' WHERE id = 9050;
UPDATE image SET alt = 'VATTI Flexi Hob C836G in AG Grey, front view' WHERE id = 9051;

INSERT INTO product_colourway (product_id, position, name, image_id)
SELECT id, 1, 'Black', 9050 FROM product WHERE slug = 'vatti-flexi-hob-c836g';
INSERT INTO product_colourway (product_id, position, name, image_id)
SELECT id, 2, 'AG Grey', 9051 FROM product WHERE slug = 'vatti-flexi-hob-c836g';
`;

writeFileSync(SQL_OUT, sql);
console.log(`\nwrote ${path.relative(ROOT, SQL_OUT)}`);
console.log("next: pnpm media:upload, then pnpm db:build");
